/** "provider/model" — provider ids never contain "/". */
export function refOf(provider: string, model: string) {
  return `${provider}/${model}`;
}
export function parseRef(ref: string): { provider: string; model: string | null } {
  const i = ref.indexOf("/");
  return i < 0 ? { provider: ref, model: null } : { provider: ref.slice(0, i), model: ref.slice(i + 1) };
}

