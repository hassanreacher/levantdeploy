"use client";

import { useState } from "react";
import { RefreshCw, Sparkles, Stethoscope } from "lucide-react";
import { api } from "@/lib/client/api";
import { AI_OPEN_EVENT, type AiOpenDetail } from "@/lib/ai/types";
import { Button, useToast, type ButtonProps } from "@/components/ui";
import { Markdown } from "./markdown";

export function fixPrompt(d: { number: number; errorStep?: string | null; errorMessage?: string | null }) {
  const err = d.errorMessage ? `: "${d.errorMessage.replace(/\s+/g, " ").slice(0, 300)}"` : "";
  return `Deployment #${d.number} failed${d.errorStep ? ` during ${d.errorStep.toLowerCase()}` : ""}${err}. Diagnose why and propose a fix.`;
}

/** Opens the global assistant pre-filled with the failure (and sends it). Usable on any page under /{team}. */
export function openAssistant(detail: AiOpenDetail) {
  window.dispatchEvent(new CustomEvent<AiOpenDetail>(AI_OPEN_EVENT, { detail }));
}

/**
 * "Ask AI to fix" — mount on the deployment page when status is ERROR:
 *   <AskAiButton deployment={{ number: d.number, errorStep: d.errorStep, errorMessage: d.errorMessage }} />
 */
export function AskAiButton({ deployment, onAsk, ...rest }: { deployment: { number: number; errorStep?: string | null; errorMessage?: string | null }; onAsk?: (prompt: string) => void } & Omit<ButtonProps, "onClick">) {
  return (
    <Button
      variant="secondary"
      size="sm"
      leftIcon={<Sparkles className="h-3.5 w-3.5 text-accent" />}
      {...rest}
      onClick={() => {
        const prompt = fixPrompt(deployment);
        if (onAsk) onAsk(prompt);
        else openAssistant({ prompt, autoSend: true });
      }}
    >
      Ask AI to fix
    </Button>
  );
}

export type DiagnosisView = { summary: string; source: "ai" | "heuristic"; model: string | null; at: string };

/**
 * Banner for a failed deployment: the stored auto-diagnosis (deployment.meta.aiDiagnosis) + "Ask AI to fix".
 *   <AiDiagnosisBanner deploymentId={d.id} deployment={{ number, errorStep, errorMessage }} initial={readDiagnosis(d.meta)} />
 */
export function AiDiagnosisBanner({ deploymentId, deployment, initial, onAsk }: { deploymentId: string; deployment: { number: number; errorStep?: string | null; errorMessage?: string | null }; initial: DiagnosisView | null; onAsk?: (prompt: string) => void }) {
  const toast = useToast();
  const [dx, setDx] = useState<DiagnosisView | null>(initial);
  const [running, setRunning] = useState(false);
  const run = async () => {
    setRunning(true);
    try {
      const r = await api<{ diagnosis: DiagnosisView | null }>(`/api/v1/ai/deployments/${deploymentId}/diagnose`, { method: "POST", body: {} });
      setDx(r.diagnosis);
    } catch (e) {
      toast.error("Diagnosis failed", (e as Error).message);
    } finally {
      setRunning(false);
    }
  };
  return (
    <div className="overflow-hidden rounded-xl border border-danger/30 bg-danger/5" data-testid="ai-diagnosis-banner">
      <div className="flex flex-wrap items-center gap-2 border-b border-danger/20 px-4 py-2.5">
        <Stethoscope className="h-4 w-4 text-danger" />
        <p className="flex-1 text-[13px] font-medium text-fg">{dx ? (dx.source === "ai" ? "AI diagnosis" : "Automatic diagnosis") : `Deployment #${deployment.number} failed`}</p>
        <Button size="sm" variant="ghost" onClick={run} loading={running} leftIcon={!running ? <RefreshCw className="h-3.5 w-3.5" /> : undefined}>
          {dx ? "Re-run" : "Diagnose"}
        </Button>
        <AskAiButton deployment={deployment} onAsk={onAsk} />
      </div>
      <div className="px-4 py-3">
        {dx ? (
          <>
            <Markdown text={dx.summary} className="text-[13.5px]" />
            <p className="mt-2 text-[11.5px] text-subtle">
              {dx.source === "ai" ? `Generated by ${dx.model ?? "the agent"}` : "Pattern-based (AI not configured)"} · {new Date(dx.at).toLocaleString()}
            </p>
          </>
        ) : (
          <p className="text-[13px] text-muted">{deployment.errorMessage ?? "No diagnosis yet. Run one, or ask the agent to investigate and propose a fix."}</p>
        )}
      </div>
    </div>
  );
}
