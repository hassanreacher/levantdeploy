import { check, eq, assert, ok, sql, until, client } from "./lib";
import type { Ctx } from "./auth";

/** Schema used by the database / realtime / graphql checks — created through the platform SQL API (POST …/sql). */
export const SCHEMA_SQL = `
create schema if not exists compat_private;
drop table if exists public.compat_todos, public.compat_cities, public.compat_countries, public.compat_messages cascade;
create table public.compat_countries (id bigint primary key, name text not null unique, code text not null);
create table public.compat_cities (
  id bigint generated by default as identity primary key,
  name text not null,
  country_id bigint not null references public.compat_countries(id) on delete cascade,
  population integer not null default 0
);
create table public.compat_todos (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  title text not null,
  done boolean not null default false,
  priority integer not null default 1,
  slug text unique,
  created_at timestamptz not null default now()
);
create table public.compat_messages (
  id bigint generated by default as identity primary key,
  room text not null,
  body text not null,
  user_id uuid default auth.uid()
);
alter table public.compat_messages replica identity full;
alter table public.compat_countries enable row level security;
alter table public.compat_cities enable row level security;
alter table public.compat_todos enable row level security;
alter table public.compat_messages enable row level security;
create policy "countries are public" on public.compat_countries for select to anon, authenticated using (true);
create policy "cities are public" on public.compat_cities for select to anon, authenticated using (true);
create policy "own todos: select" on public.compat_todos for select to authenticated using (user_id = (select auth.uid()));
create policy "own todos: insert" on public.compat_todos for insert to authenticated with check (user_id = (select auth.uid()));
create policy "own todos: update" on public.compat_todos for update to authenticated using (user_id = (select auth.uid())) with check (user_id = (select auth.uid()));
create policy "own todos: delete" on public.compat_todos for delete to authenticated using (user_id = (select auth.uid()));
create policy "messages readable by signed-in users" on public.compat_messages for select to authenticated using (true);
create policy "messages: insert own" on public.compat_messages for insert to authenticated with check (user_id = (select auth.uid()));
create policy "messages: update own" on public.compat_messages for update to authenticated using (user_id = (select auth.uid()));
create policy "messages: delete own" on public.compat_messages for delete to authenticated using (user_id = (select auth.uid()));
grant select on public.compat_countries, public.compat_cities to anon, authenticated;
grant select, insert, update, delete on public.compat_todos, public.compat_messages to authenticated;
grant all on all tables in schema public to service_role;
insert into public.compat_countries (id, name, code) values (1, 'Lebanon', 'LB'), (2, 'Jordan', 'JO'), (3, 'Syria', 'SY');
insert into public.compat_cities (name, country_id, population) values
  ('Beirut', 1, 2400000), ('Tripoli', 1, 730000), ('Byblos', 1, 40000), ('Amman', 2, 4000000), ('Irbid', 2, 2000000), ('Aleppo', 3, 2100000);
create or replace function public.compat_add(a integer, b integer) returns integer language sql immutable as $$ select a + b $$;
create or replace function public.compat_city_count(country text) returns integer language sql stable as $$
  select count(*)::int from public.compat_cities c join public.compat_countries k on k.id = c.country_id where k.code = country $$;
create or replace function public.compat_whoami() returns json language sql stable as $$
  select json_build_object('uid', auth.uid(), 'role', auth.role(), 'email', auth.jwt() ->> 'email') $$;
grant execute on function public.compat_add, public.compat_city_count, public.compat_whoami to anon, authenticated;
do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'compat_messages') then
    alter publication supabase_realtime add table public.compat_messages;
  end if;
end $$;
notify pgrst, 'reload schema';
`;

export async function dbSuite(ctx: Ctx) {
  const D = "database";
  const { a, b } = ctx.users;

  await check(D, "PostgREST sees the new tables after `notify pgrst, 'reload schema'`", async () => {
    await until(async () => !(await ctx.anon.from("compat_countries").select("id").limit(1)).error, "schema cache reload", 20_000);
  });

  await check(D, "select with filters (eq / gt / in / ilike / or) + order", async () => {
    const r = ok(await ctx.anon.from("compat_cities").select("name,population").eq("country_id", 1).gt("population", 50_000).order("population", { ascending: false }), "select");
    eq(r.map((x) => x.name), ["Beirut", "Tripoli"], "eq+gt+order");
    const r2 = ok(await ctx.anon.from("compat_cities").select("name").in("country_id", [2, 3]).ilike("name", "%a%").order("name"), "in+ilike");
    eq(r2.map((x) => x.name), ["Aleppo", "Amman"], "in+ilike");
    const r3 = ok(await ctx.anon.from("compat_cities").select("name").or("name.eq.Byblos,population.gte.4000000").order("name"), "or");
    eq(r3.map((x) => x.name), ["Amman", "Byblos"], "or");
  });

  await check(D, "range + count: 'exact'", async () => {
    const r = await ctx.anon.from("compat_cities").select("name", { count: "exact" }).order("id").range(1, 3);
    ok(r, "range");
    eq(r.data!.length, 3, "page size");
    eq(r.count, 6, "count");
  });

  await check(D, "head count (count only, no rows)", async () => {
    const r = await ctx.anon.from("compat_cities").select("*", { count: "exact", head: true }).eq("country_id", 1);
    ok(r, "head");
    eq(r.count, 3, "count");
  });

  await check(D, "single() / maybeSingle()", async () => {
    eq(ok(await ctx.anon.from("compat_countries").select("code").eq("id", 2).single(), "single").code, "JO", "code");
    eq(ok(await ctx.anon.from("compat_countries").select("code").eq("id", 99).maybeSingle(), "maybeSingle"), null, "missing row");
  });

  await check(D, "embedded relations (many-to-one and one-to-many)", async () => {
    const r = ok(await ctx.anon.from("compat_cities").select("name, country:compat_countries(name, code)").eq("name", "Amman").single(), "m2o");
    eq((r.country as unknown as { code: string }).code, "JO", "embedded country");
    const r2 = ok(await ctx.anon.from("compat_countries").select("name, compat_cities(name)").eq("code", "LB").order("name", { referencedTable: "compat_cities" }).single(), "o2m");
    eq((r2.compat_cities as { name: string }[]).map((c) => c.name), ["Beirut", "Byblos", "Tripoli"], "embedded cities");
  });

  await check(D, "rpc() to SQL functions (scalar + with table access)", async () => {
    eq(ok(await ctx.anon.rpc("compat_add", { a: 20, b: 22 }), "rpc add"), 42, "compat_add");
    eq(ok(await ctx.anon.rpc("compat_city_count", { country: "LB" }), "rpc count"), 3, "compat_city_count");
  });

  await check(D, "rpc() sees the caller's JWT (auth.uid(), auth.role())", async () => {
    const r = ok(await a.sb.rpc("compat_whoami"), "rpc") as { uid: string; role: string; email: string };
    eq(r.uid, a.id, "uid");
    eq(r.role, "authenticated", "role");
    eq((ok(await ctx.anon.rpc("compat_whoami"), "rpc anon") as { role: string }).role, "anon", "anon role");
  });

  let todoId = 0;
  await check(D, "insert (returning) as a signed-in user", async () => {
    const r = ok(await a.sb.from("compat_todos").insert([{ title: "write docs", priority: 2 }, { title: "ship", priority: 3 }]).select(), "insert");
    eq(r.length, 2, "rows");
    eq(r[0]!.user_id, a.id, "user_id default auth.uid()");
    todoId = r[0]!.id as number;
  });

  await check(D, "update with filter + returning", async () => {
    const r = ok(await a.sb.from("compat_todos").update({ done: true }).eq("id", todoId).select("id,done").single(), "update");
    eq(r.done, true, "done");
  });

  await check(D, "upsert (on conflict) inserts then updates", async () => {
    ok(await a.sb.from("compat_todos").upsert({ slug: "same-slug", title: "v1" }, { onConflict: "slug" }), "upsert 1");
    const r = ok(await a.sb.from("compat_todos").upsert({ slug: "same-slug", title: "v2" }, { onConflict: "slug" }).select("title"), "upsert 2");
    eq(r.map((x) => x.title), ["v2"], "title");
    const n = await a.sb.from("compat_todos").select("*", { count: "exact", head: true }).eq("slug", "same-slug");
    eq(n.count, 1, "one row");
  });

  await check(D, "delete with filter", async () => {
    ok(await a.sb.from("compat_todos").delete().eq("slug", "same-slug"), "delete");
    eq(ok(await a.sb.from("compat_todos").select("id").eq("slug", "same-slug"), "select").length, 0, "rows left");
  });

  await check(D, "RLS: another user cannot see the rows", async () => {
    eq(ok(await a.sb.from("compat_todos").select("id"), "a").length, 2, "user A sees own rows");
    eq(ok(await b.sb.from("compat_todos").select("id"), "b").length, 0, "user B sees nothing");
  });

  await check(D, "RLS: another user cannot update or delete the rows", async () => {
    eq(ok(await b.sb.from("compat_todos").update({ title: "hacked" }).eq("id", todoId).select(), "b update").length, 0, "rows updated by B");
    eq(ok(await b.sb.from("compat_todos").delete().eq("id", todoId).select(), "b delete").length, 0, "rows deleted by B");
    eq(ok(await a.sb.from("compat_todos").select("title").eq("id", todoId).single(), "a").title, "write docs", "title unchanged");
  });

  await check(D, "RLS: inserting a row for another user is refused (WITH CHECK)", async () => {
    const r = await b.sb.from("compat_todos").insert({ title: "spoof", user_id: a.id });
    assert(r.error, "insert should fail");
    eq(r.error.code, "42501", "error code");
  });

  await check(D, "RLS: anon cannot read or write user tables", async () => {
    eq(ok(await ctx.anon.from("compat_todos").select("id"), "anon select").length, 0, "anon rows");
    const r = await ctx.anon.from("compat_todos").insert({ title: "anon" });
    assert(r.error, "anon insert should fail");
    return `insert → ${r.error.code}`;
  });

  await check(D, "service_role bypasses RLS", async () => {
    const r = ok(await ctx.admin.from("compat_todos").select("id,user_id"), "service select");
    assert(r.length >= 2 && r.every((x) => x.user_id === a.id), `rows ${r.length}`);
  });

  await check(D, "PostgREST error shape (unknown column → 42703 / PGRST)", async () => {
    const r = await ctx.anon.from("compat_cities").select("nope");
    assert(r.error, "expected an error");
    assert(["42703", "PGRST204"].includes(r.error.code), `code ${r.error.code}`);
    return r.error.code;
  });

  await check(D, "objects created through the SQL API belong to `postgres` (hosted SQL-editor semantics)", async () => {
    const r = await sql(ctx.ref, "select string_agg(distinct tableowner, ',') as owners from pg_tables where tablename like 'compat\\_%'");
    eq(r.rows[0]!.owners, "postgres", "table owner");
  });

  await check(D, "platform SQL API runs DDL/DML and returns rows", async () => {
    const r = await sql(ctx.ref, "select count(*)::int as n from public.compat_cities");
    eq(r.rows[0]!.n, "6", "n");
  });

  await check(D, "typed client against a fresh connection (no session) still works", async () => {
    eq(ok(await client(ctx.url, ctx.anonKey).from("compat_countries").select("code").order("id"), "select").map((x) => x.code), ["LB", "JO", "SY"], "codes");
  });
}
