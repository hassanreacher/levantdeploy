#!/usr/bin/env node
/**
 * Bundles the worker (src/worker/index.ts + every src/worker/processors/*.ts) into dist/worker.js (ops area).
 *
 *   node scripts/build-worker.mjs        → dist/worker.js   (run with: node dist/worker.js)
 *
 * The dev worker (`npm run worker`, tsx) discovers processors by reading src/worker/processors/ at runtime.
 * A bundle can't do that, so this script generates an entry that imports every processor statically first
 * and then the worker entry. dist/processors/ is created empty so the runtime directory scan finds nothing
 * extra to load (all processors are already registered by the bundle).
 *
 * npm packages stay external (node_modules is shipped in the image: Prisma engines, native ssh2, BullMQ Lua scripts).
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const procDir = path.join(root, "src/worker/processors");
const outDir = path.join(root, "dist");

const processors = fs
  .readdirSync(procDir)
  .filter((f) => /\.(ts|js|mjs)$/.test(f) && !f.endsWith(".d.ts") && !f.includes(".test."))
  .sort();

fs.rmSync(outDir, { recursive: true, force: true });
fs.mkdirSync(path.join(outDir, "processors"), { recursive: true });

const entry = [
  "// generated by scripts/build-worker.mjs",
  ...processors.map((f) => `import "./processors/${f.replace(/\.(ts|js|mjs)$/, "")}";`),
  'import "./index";',
  "",
].join("\n");

const result = await build({
  stdin: { contents: entry, resolveDir: path.join(root, "src/worker"), sourcefile: "worker-entry.ts", loader: "ts" },
  bundle: true,
  platform: "node",
  target: "node22",
  format: "cjs",
  outfile: path.join(outDir, "worker.js"),
  packages: "external",
  tsconfig: path.join(root, "tsconfig.json"),
  sourcemap: "linked",
  logLevel: "info",
  // `server-only` throws when imported outside React Server Components; the worker never renders RSC.
  alias: { "server-only": path.join(root, "scripts/empty-module.cjs") },
  define: { "process.env.LEVANT_WORKER_BUNDLE": '"1"' },
  metafile: true,
});

const inputs = Object.keys(result.metafile.inputs).filter((p) => p.includes("src/worker/processors/"));
console.log(`[build-worker] dist/worker.js with ${processors.length} processor file(s): ${processors.join(", ")} (${inputs.length} bundled)`);
